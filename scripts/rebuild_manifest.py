#!/usr/bin/env python3
"""Rebuild resources/manifest.toml from the wordlists actually on disk."""
import hashlib, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WL = os.path.join(ROOT, 'resources', 'wordlists')
MANIFEST = os.path.join(ROOT, 'resources', 'manifest.toml')

LABELS = {
    'passwords': 'leaked password lists', 'creds': 'default credentials',
    'users': 'username lists', 'usernames': 'username lists',
    'dns': 'DNS and subdomain discovery', 'web': 'web content discovery',
    'http': 'HTTP methods', 'dirs': 'directory discovery',
    'params': 'parameter discovery', 'payloads': 'injection payloads',
    'wifi': 'wireless passwords', 'wireless': 'wireless passwords',
    'ssh': 'SSH credentials', 'smb': 'SMB credentials',
    'ad': 'Active Directory credentials', 'db': 'database credentials',
    'fuzz': 'fuzzing payloads', 'rules': 'hashcat rules',
    'cloud': 'cloud keywords', 'mobile': 'mobile endpoints',
    'ctf': 'CTF flag patterns',
}

def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()

entries = []
for cat in sorted(os.listdir(WL)):
    d = os.path.join(WL, cat)
    if not os.path.isdir(d):
        continue
    for name in sorted(os.listdir(d)):
        path = os.path.join(d, name)
        if not os.path.isfile(path):
            continue
        with open(path, 'rb') as f:
            data = f.read()
        lines = sum(1 for _ in open(path, 'r', errors='ignore'))
        wid = f'{cat}/{name}'
        rel = f'wordlists/{cat}/{name}'
        entries.append((wid, rel, lines, len(data), sha256(path), LABELS.get(cat, cat)))

out = [
    '# LOUTE resource manifest - schema 1',
    '# Generated by scripts/rebuild_manifest.py from real SecLists data.',
    '# Sources and licenses: resources/ATTRIBUTION.md',
    '',
]
for wid, rel, lines, nbytes, digest, source in entries:
    out += [
        '[[wordlist]]',
        f"id = '{wid}'",
        f"path = '{rel}'",
        f'lines = {lines}',
        f'bytes = {nbytes}',
        f"sha256 = '{digest}'",
        "license = 'MIT'",
        f"source = 'SecLists ({source}), see ATTRIBUTION.md'",
        "pack = 'core'",
        '',
    ]

open(MANIFEST, 'w').write('\n'.join(out))
print(f'Manifest rebuilt: {len(entries)} wordlists, {sum(e[2] for e in entries)} total lines')
